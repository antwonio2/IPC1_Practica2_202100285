    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try{
            int id = Integer.parseInt(jTextField1.getText().trim());
            Personajes p = Menu.gestor.buscarId(id);
        
            if (p != null){
                
                jTextField8.setText(p.getNombre());
                jTextField2.setText(p.getArma());
                jTextField3.setText(String.valueOf(p.getHp()));
                jTextField4.setText(String.valueOf(p.getAtaque()));
                jTextField5.setText(String.valueOf(p.getVelocidad()));
                jTextField6.setText(String.valueOf(p.getAgilidad()));
                jTextField7.setText(String.valueOf(p.getDefensa()));                  
            }else{
                JOptionPane.showMessageDialog(this, "No se encontro personaje con ese ig");
            }
        }
        
        catch(NumberFormatException e){
            JOptionPane.showMessageDialog(this, "Ingrese un Id valido por favor");
                    }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        try{
            int id = Integer.parseInt(jTextField1.getText().trim());
            Personajes p = Menu.gestor.buscarId(id);
            
            if (p!=null){
            
                p.setNombre(jTextField8.getText().trim());
                p.setArma(jTextField2.getText().trim());
                p.setHp(Integer.parseInt(jTextField3.getText().trim()));
                p.setAtaque(Integer.parseInt(jTextField4.getText().trim()));
                p.setVelocidad(Integer.parseInt(jTextField5.getText().trim()));
                p.setAgilidad(Integer.parseInt(jTextField6.getText().trim()));
                p.setDefensa(Integer.parseInt(jTextField7.getText().trim()));
            
                JOptionPane.showMessageDialog(this, "Cambios hechos");
                this.dispose();
            }
        }catch (NumberFormatException e){
        
        }
    }//GEN-LAST:event_jButton3ActionPerformed

