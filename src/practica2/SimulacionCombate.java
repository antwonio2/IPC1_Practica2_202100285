    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        int id1 = jComboBox1.getSelectedIndex();
        int id2 = jComboBox2.getSelectedIndex();
        
        if (id1 == id2){
            javax.swing.JOptionPane.showMessageDialog(this, "Elige personajes distintos");
            return;
        }

        Personajes p1 = Menu.gestor.getPersonajes()[id1];
        Personajes p2 = Menu.gestor.getPersonajes()[id2];
        
        if (p1.getHp()<=0 || p2.getHp()<=0){
            JOptionPane.showMessageDialog(this, "Ambos deben estar vivos");
            return;
        }
        
        Pokemon h1 = new Pokemon(p1, p2, jTextPane1);
        Pokemon h2 = new Pokemon(p2, p1, jTextPane1);
        
        h1.start();
        h2.start();  
     
    }//GEN-LAST:event_jButton2ActionPerformed

