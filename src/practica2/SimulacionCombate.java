    class Pokemon extends Thread{
        private Personajes pokemon1;
        private Personajes pokemon2;
        private JTextPane bitacora;
    
        public Pokemon(Personajes pokemon1, Personajes pokemon2, JTextPane bitacora){
        this.pokemon1 = pokemon1;
        this.pokemon2 = pokemon2;
        this.bitacora = bitacora;
        
        }
        
        @Override
       public void run (){
           while(pokemon1.getHp()>0 && pokemon2.getHp()>0){
               try{
                   Thread.sleep(1000 / pokemon1.getVelocidad());
               }catch(InterruptedException e){
                e.printStackTrace();
        }

        int dano = pokemon1.getAtaque() - pokemon2.getDefensa();
        if (dano<0)dano = 0;

        boolean esquiva = Math.random()<(pokemon2.getAgilidad()/10.0);
        if (esquiva){
            jTextPane1.setText(jTextPane1.getText() + pokemon1.getNombre() + " atacó a " + pokemon2.getNombre() + " pero esquivó!\n");
    } else {
        pokemon2.setHp(pokemon2.getHp() - dano);
        jTextPane1.setText(jTextPane1.getText() + pokemon1.getNombre() + " atacó a " + pokemon2.getNombre() +
                " causando " + dano + " de daño. HP de " + pokemon2.getNombre() +
                " = " + pokemon2.getHp() + "\n");
    }

    if (pokemon2.getHp() <= 0) {
        jTextPane1.setText(jTextPane1.getText() + pokemon2.getNombre() + " ha sido derrotado!\n");
        break;
    }
           }
       }
    }
